# -*- coding: utf-8 -*-
"""画面不可判条目清单（单一事实来源）。

为什么要这个模块
----------------
`core/prompts.py` 的标准名称表原有 67 条，其中 11 条**从航拍视频拿不到证据**
（证件、票据、厘米级细节、必须时序的动作）。它们长期躺在名称表里，导致：

1. 评测时被当成「漏检」，把架构限制算成算法缺陷；
2. 模型偶尔硬报，产生无法证伪的误报；
3. 报告里出现「本批未检出 XX」这种对现场毫无意义的话。

v1.13.44 起这 11 条已从名称表删除，并在提示词里给出【画面不可判条目】清单
明确禁止上报。本模块给代码侧（测试、统计、报告）提供同一份清单，避免
两边各写一份、慢慢漂移。

注意：编号是**原名称表编号**，保留是为了兼容其它判据里的「报 XX 号」交叉引用。
"""

# 编号 -> (名称, 不可判原因)
UNDETECTABLE = {
    17: ("特种作业人员无证上岗", "证件不在画面里"),
    19: ("无作业票/未交底作业", "票据不在画面里"),
    20: ("作业管理不规范", "兜底类目，无可证伪的视觉定义"),
    24: ("消防器材缺失/现场吸烟", "器材可能在箱内/室内；烟头不可辨"),
    36: ("外电线路安全距离不足", "需电压等级 + 精确测距"),
    38: ("起重机械受力构件缺陷", "裂纹/锈蚀/变形是厘米级细节"),
    39: ("吊索具破损/报废", "钢丝绳断丝断股需 <1px 分辨率"),
    41: ("竖井提升装置安全装置缺失", "防坠器/限位是装置内部细节"),
    47: ("高空抛物/工具材料下抛", "必须时序，单帧不可判"),
    50: ("吊装作业无专人指挥", "需识别手势/指挥动作"),
    51: ("配电箱门未跨接/未上锁", "跨接线厘米级；未上锁不可见"),
}

# 编号集合（便于比较与断言）
UNDETECTABLE_NUMS = tuple(sorted(UNDETECTABLE))

# 名称集合（报告/统计按标题匹配用）
UNDETECTABLE_TITLES = frozenset(t for t, _ in UNDETECTABLE.values())


def is_undetectable(title):
    """该标题是否属于「画面不可判」条目（按名称精确匹配）。"""
    return str(title or "").strip() in UNDETECTABLE_TITLES


def reason_of(title):
    """返回不可判原因；不在清单里返回空串。"""
    key = str(title or "").strip()
    for t, r in UNDETECTABLE.values():
        if t == key:
            return r
    return ""


def summary():
    """一行摘要，供日志/报告脚注使用。"""
    return "画面不可判 %d 条（编号 %s），已从名称表移除" % (
        len(UNDETECTABLE), "/".join(str(n) for n in UNDETECTABLE_NUMS))
