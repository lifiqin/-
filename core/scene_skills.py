def get_scene_type_skill(scene_type):
    """返回场景类型（界面下拉的7项）专属skill；未命中兜底'通用安全检查'"""
    if not scene_type:
        return _assemble(SCENE_TYPE_SKILLS["通用安全检查"])

    skill = None
    if scene_type in SCENE_TYPE_SKILLS:
        skill = SCENE_TYPE_SKILLS[scene_type]
    elif scene_type in _SCENE_TYPE_ALIASES:
        skill = SCENE_TYPE_SKILLS[_SCENE_TYPE_ALIASES[scene_type]]
    else:
        for key in SCENE_TYPE_SKILLS:
            if key != "通用安全检查" and key in scene_type:
                skill = SCENE_TYPE_SKILLS[key]
                break
    if skill is None:
        for alias, key in _SCENE_TYPE_ALIASES.items():
            if alias in scene_type:
                skill = SCENE_TYPE_SKILLS[key]
                break
    if skill is None:
        skill = SCENE_TYPE_SKILLS["通用安全检查"]
    return _assemble(skill)


