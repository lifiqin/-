# 基坑判定的强/弱证据（2026-09-17 误报治理）：
# "土方堆放""场地平整""边坡"这类字样在非基坑场景（材料堆放、场地硬化）里非常常见，
# 单凭它们就把场景判成"基坑开挖"，会让场景技能注入和分段标签整体跑偏。
# 强词 = 直接描述坑体几何的字眼；弱词只作为辅助证据（至少两个同时出现才够格）。
_PIT_STRONG_KWS = ("基坑", "基槽", "深坑", "沟槽", "桩孔", "沉井", "坑内")
_PIT_WEAK_KWS = ("开挖", "土方", "边坡", "垫层")


def match_scene_key(text):
    """从场景描述文本匹配最贴近的场景skill键；无命中返回None

    基坑开挖采用强/弱证据加权（其余类别仍按命中数取最高）：
    - 含任一强词（直接描述坑体几何）→ 判基坑开挖
    - 无强词但弱词 >= 2（如"土方开挖"）→ 判基坑开挖
    - 只有单个弱词（如"土方堆放"）→ 不判基坑开挖，交给其他类别竞争
    """
    if not text:
        return None
    best, best_hits = None, 0
    for key, kws in _SCENE_KEYWORDS.items():
        if key == "基坑开挖":
            strong = sum(1 for kw in _PIT_STRONG_KWS if kw in text)
            weak = sum(1 for kw in _PIT_WEAK_KWS if kw in text)
            if strong == 0 and weak < 2:
                continue        # 证据不足，不参与竞争（防止土方堆放→基坑）
            hits = strong * 2 + weak
        else:
            hits = sum(1 for kw in kws if kw in text)
        if hits > best_hits:
            best, best_hits = key, hits
    return best
